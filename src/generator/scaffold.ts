import type { WorkflowDefinition } from "../workflow/types.js";
import type { GeneratorEndpoint } from "./types.js";

/** Generate `src/rc-client.ts` — a Rocket.Chat HTTP client implementing WorkflowClient. */
export function generateRcClient(): string {
  return `/**
 * Rocket.Chat HTTP client. Implements the engine's WorkflowClient contract:
 *   request(method, path, { auth, body }) -> { ok, status, data }
 *
 * Auth priority:
 *   1. ROCKETCHAT_AUTH_TOKEN + ROCKETCHAT_USER_ID — used directly
 *   2. ROCKETCHAT_USER + ROCKETCHAT_PASSWORD — auto-login at startup
 *   3. neither — unconfigured (auth'd calls will fail)
 * Generated by mcp-server-generator.
 */
const config = {
  baseUrl: process.env.ROCKETCHAT_URL || "http://localhost:3000",
  authToken: process.env.ROCKETCHAT_AUTH_TOKEN || "",
  userId: process.env.ROCKETCHAT_USER_ID || "",
};

const REQUEST_TIMEOUT_MS = Number(process.env.ROCKETCHAT_REQUEST_TIMEOUT_MS) || 30000;

export interface ApiResponse {
  ok: boolean;
  status: number;
  data: unknown;
}

async function parseBody(res: Response): Promise<unknown> {
  const raw = await res.text();
  if (raw.length === 0) return null;
  const contentType = res.headers.get("content-type") || "";
  if (contentType.includes("json")) {
    try {
      return JSON.parse(raw);
    } catch {
      return raw;
    }
  }
  return raw;
}

let initialized = false;

export async function initAuth(): Promise<void> {
  if (initialized) return;
  initialized = true;

  if (config.authToken && config.userId) {
    console.error("Using pre-existing Rocket.Chat auth tokens.");
    return;
  }

  const user = process.env.ROCKETCHAT_USER || "";
  const password = process.env.ROCKETCHAT_PASSWORD || "";
  if (!user || !password) {
    console.error("No Rocket.Chat credentials set — starting unconfigured.");
    return;
  }

  try {
    const res = await fetch(config.baseUrl + "/api/v1/login", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ user, password }),
    });
    const data = (await parseBody(res)) as {
      data?: { authToken?: string; userId?: string };
    };
    if (res.ok && data?.data?.authToken && data.data.userId) {
      config.authToken = data.data.authToken;
      config.userId = data.data.userId;
      console.error("Authenticated as " + user);
    } else {
      console.error("Rocket.Chat login failed (HTTP " + res.status + ").");
    }
  } catch (err) {
    console.error("Could not reach Rocket.Chat for login: " + String(err));
  }
}

function buildUrl(path: string): string {
  return path.startsWith("http") ? path : config.baseUrl + path;
}

class RocketChatClient {
  async request(
    method: string,
    path: string,
    options: { auth?: boolean; body?: Record<string, unknown> } = {},
  ): Promise<ApiResponse> {
    const headers: Record<string, string> = { "Content-Type": "application/json" };
    if (options.auth) {
      headers["X-Auth-Token"] = config.authToken;
      headers["X-User-Id"] = config.userId;
    }

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
    try {
      const res = await fetch(buildUrl(path), {
        method,
        headers,
        ...(options.body !== undefined ? { body: JSON.stringify(options.body) } : {}),
        signal: controller.signal,
      });
      const data = await parseBody(res);
      return { ok: res.ok, status: res.status, data };
    } catch (err) {
      return {
        ok: false,
        status: 0,
        data: err instanceof Error ? err.message : String(err),
      };
    } finally {
      clearTimeout(timer);
    }
  }
}

export const client = new RocketChatClient();
`;
}

