export function generateEnvExample(usesSampling: boolean): string {
  let env = `# Rocket.Chat connection
ROCKETCHAT_URL=http://localhost:3000

# Credentials — the server acts as this user
ROCKETCHAT_USER=your-username
ROCKETCHAT_PASSWORD=your-password

# Or token auth (takes priority over user/password)
# ROCKETCHAT_AUTH_TOKEN=
# ROCKETCHAT_USER_ID=
`;
  if (usesSampling) {
    env += `
# Sampling steps request the MCP client's LLM, so no extra key is required when
# your MCP client supports sampling.
`;
  }
  return env;
}

export function generateReadme(
  serverName: string,
  workflows: WorkflowDefinition[],
  endpoints: GeneratorEndpoint[],
): string {
  const date = new Date().toISOString().split("T")[0];
  const workflowRows = workflows
    .map((w) => {
      const features: string[] = [];
      if (w.usesSampling) features.push("AI");
      if (w.usesElicitation) features.push("Human-in-loop");
      const badge = features.length > 0 ? features.join(", ") : "Automation";
      return `| \`${w.name}\` | ${w.description} | ${w.steps.length} | ${badge} |`;
    })
    .join("\n");
  const endpointRows = endpoints
    .map(
      (ep) =>
        `| \`${ep.operationId}\` | \`${ep.method.toUpperCase()}\` | \`${ep.path}\` |`,
    )
    .join("\n");

  return `# ${serverName}

A workflow-based [MCP](https://modelcontextprotocol.io/) server for Rocket.Chat,
generated by **mcp-server-generator**. Each tool runs a multi-step workflow that
chains API calls, AI sampling, and user confirmation behind one call.

> Generated on ${date}

## Quick start

\`\`\`bash
npm install
cp .env.example .env   # fill in your Rocket.Chat credentials
npm start
\`\`\`

## Workflow tools

| Tool | Description | Steps | Features |
|------|-------------|-------|----------|
${workflowRows}

## API endpoints used

| operationId | Method | Path |
|-------------|--------|------|
${endpointRows}

## Project layout

\`\`\`
${serverName}/
├── src/
│   ├── server.ts       # entry point — wires tools to stdio transport
│   ├── rc-client.ts    # Rocket.Chat HTTP client
│   ├── endpoints.ts    # operationId -> method + path
│   ├── engine/         # vendored workflow engine
│   └── tools/          # one file per workflow
├── .env.example
├── package.json
├── tsconfig.json
└── README.md
\`\`\`

---

*Generated by mcp-server-generator.*
`;
}
